package com.yongsa.combat;

/** 보스 특수 공격 종류 (FR-전투-10). 모두 공격 전에 예고(자세·바닥 표시)를 보여준다. */
public enum BossPattern {
    /** 마왕: 용사 발밑에 원을 보여준 뒤 내려친다. */
    SLAM,
    /** 마왕: 돌진할 방향에 선을 보여준 뒤 빠르게 돌진한다. */
    CHARGE,
    /** 마왕: 힘을 모은 뒤 사방으로 탄을 쏜다. */
    NOVA,
    /** 좀비킹: 용사에게 세 번 연달아 달려든다. 매번 방향선을 먼저 보여준다. */
    RUSH,
    /** 리치: 용사가 있던 자리마다 예고 뒤 뼈 가시가 솟는다 (따라가지 않는다). */
    BONE_SPIKE,
    /** 리치: 잡몹(되살아난 해골)을 불러낸다. */
    SUMMON,
    /** 마룡: 아래를 보며 울부짖으면 맵 세 곳에 독구름. */
    POISON_HOWL,
    /** 마룡: 위를 보며 울부짖으면 번개 10번. 맞으면 감전(스킬 봉인). */
    LIGHTNING_HOWL,
    /** 마룡: 엉덩이를 들면 꼬리에서 얼음 덩이가 사방으로. 맞으면 빙결. */
    ICE_TAIL,
    /** 마룡: 3~5초 회전하며 화염 브레스를 사방으로. 맞으면 화상. */
    FIRE_SPIN,
    /** 마왕 2페이즈: 용사 주변 바닥에서 촉수가 솟는다. */
    TENTACLE
}
