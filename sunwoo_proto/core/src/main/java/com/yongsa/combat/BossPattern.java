package com.yongsa.combat;

/** 보스 특수 공격 종류 (FR-전투-10). 모두 공격 전에 예고(자세·바닥 표시)를 보여준다. */
public enum BossPattern {
    /** 마왕: 용사 발밑에 원을 보여준 뒤 내려친다. */
    SLAM,
    /** 마왕: 돌진할 방향에 선을 보여준 뒤 빠르게 돌진한다. */
    CHARGE,
    /** 마왕: 힘을 모은 뒤 사방으로 탄을 쏜다. */
    NOVA,
    /** 좀비킹: 용사에게 세 번 연달아 달려든다. 매번 방향선을 먼저 보여준다. 세 번째 뒤에는 2.5초 기절. */
    RUSH,
    /** 리치: 용사가 있던 자리마다 예고 뒤 뼈 가시가 솟는다 (따라가지 않는다). */
    BONE_SPIKE,
    /** 리치: 잡몹(되살아난 해골)을 불러낸다. */
    SUMMON,
    /** 마룡: 아래를 보며 울부짖으면 맵 세 곳에 독구름. */
    POISON_HOWL,
    /** 마룡: 위를 보며 울부짖으면 번개 10번. 맞으면 감전(스킬 봉인). */
    LIGHTNING_HOWL,
    /** 마룡: 엉덩이를 들면 꼬리에서 얼음 덩이가 사방으로. 맞으면 빙결. */
    ICE_TAIL,
    /** 마룡: 뒤돌아선 뒤 제자리에서 빙글빙글 돌며 바라보는 쪽으로 화염 구슬을 뿌린다 (3~5초). 맞으면 화상. */
    FIRE_SPIN,
    /** 마왕 2페이즈: 용사 주변 바닥에서 촉수가 솟는다. */
    TENTACLE,
    /** 리치: 뼈갑옷을 둘러 방어막을 만든다. 깨기 전에는 리치 체력이 닳지 않는다. */
    BONE_ARMOR,
    /** 리치: 용사 발밑과 무작위 위치에 점점 넓어지는 늪 → 이어서 뼈창. */
    SWAMP,
    /** 마룡: 움직이다 맵 가운데로 나타나 사방으로 태풍. 맞으면 맵 끝까지 밀려난다. */
    TYPHOON,
    /** 마왕 1: 척추를 뽑아 화면 절반 이상을 휩쓰는 횡베기. 타이밍 맞춘 회피로만 피한다. */
    BONE_WHIP,
    /** 마왕 1: 머리를 맵 구석에 던진다. 머리는 유도탄·레이저 포탑, 몸통은 맹목적으로 달려든다. */
    HEAD_TURRET,
    /** 마왕 1: 뼛가루 폭풍. 맵 전체 지속 피해, 떨어진 바위 뒤에 숨으면 막힌다. 끝나면 바위는 부서진다. */
    BONE_STORM,
    /** 마왕 1: (거리를 벌리면) 뼈 무더기로 무너져 무적 → 용사 사각지대에서 다시 모여 내려찍기. */
    COLLAPSE,
    /** 마왕 2: 허공에 거대한 눈알. 빛을 뿜을 때 눈을 바라보고 있으면 현재 체력 절반 + 기절/스킬 봉인. 등지면 된다. */
    EYES,
    /** 마왕 2: 발밑에 반전 마법진. 밟는 동안 정해진 키가 뒤바뀐다 (어떤 키가 바뀌는지는 한 번 정해지면 고정). */
    ABYSS_SIGIL,
    /** 마왕 2: 공간을 찢는다. 찢긴 곳은 전투 내내 공허(닿으면 큰 지속 피해)로 남는다. */
    VOID_TEAR,
    /** 마왕 2: 한쪽 벽으로 촉수를 찌르면 반대쪽 벽에서 튀어나와 등 뒤를 친다. */
    WARP_TENTACLE,
    /** 마왕 2: 살점의 해일. 회피로는 못 피하고 좁은 균열에 숨어야 한다 (균열은 한 번 쓰면 닫힘). */
    FLESH_TIDE,
    /** 마왕 2: 몸이 촉수·벌레 떼로 무너져 맵을 쓸고 지나간다. 이동안 모든 피해 면역, 빈틈으로 피해야 한다. */
    SWARM,
    /**
     * 마왕 2: 기형적인 팔·촉수로 공간 자체를 찢는다. 남은 전장의 20%가 한쪽에서 잘려 나가 전투 내내 공허로 남는다
     * (지나갈 수 없고, 닿으면 지속 피해). 순서와 상관없이 1분 안팎마다 끼어든다.
     */
    SPACE_REND
}
